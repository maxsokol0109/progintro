# הגדרות התחלה
a = 2
b = 3
pocet = 0

# הלולאה רצה כל עוד המרחק בין הידיים (b פחות a) גדול מהדיוק המבוקש
while b - a > 0.000001:
    
    # 1. מוצאים את האמצע
    c = (a + b) / 2
    
    # 2. מציבים במשוואה כדי לגלות איפה הפתרון
    fa = (a ** 3) - (2 * a) - 5
    fc = (c ** 3) - (2 * c) - 5
    
    # 3. מזיזים את הידיים בהתאם לתוצאה
    if fa * fc < 0:
        b = c  # הפתרון בחצי השמאלי, מזיזים את יד ימין לאמצע
    else:
        a = c  # הפתרון בחצי הימני, מזיזים את יד שמאל לאמצע
        
    # 4. מעלים את המונה ב-1 כי סיימנו סיבוב
    pocet += 1

# כשהלולאה מסתיימת, אנחנו קרובים מאוד לפתרון, שכרגע נמצא בנקודת האמצע האחרונה שחישבנו
koren = (a + b) / 2

# מדפיסים את התוצאה כפי שביקשו
print("Koren:", koren)
print("Pocet iteraci:", pocet)

